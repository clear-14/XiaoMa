def _backfill_mastery_from_profiles() -> None:
    """把历史 learning_profiles 补建成 knowledge_mastery。

    只补「还没有掌握记录」的知识点；已有记录（重复执行升级）不覆盖，
    保证迁移可重入。id 用 32 位十六进制 UUID，与 SQLAlchemy Uuid 在
    SQLite 上的存储格式一致。
    """
    conn = op.get_bind()
    existing = {
        (str(row[0]), str(row[1]))
        for row in conn.execute(
            sa.text(
                "SELECT user_id, knowledge_point_id FROM knowledge_mastery"
            )
        )
    }
    rows = conn.execute(
        sa.text(
            "SELECT user_id, knowledge_point_id, status, started_at, mastered_at "
            "FROM learning_profiles"
        )
    ).fetchall()
    for user_id, kp_id, status, started_at, mastered_at in rows:
        key = (str(user_id), str(kp_id))
        if key in existing:
            continue
        target = LEGACY_TO_MASTERY.get(status, "not_started")
        conn.execute(
            sa.text(
                "INSERT INTO knowledge_mastery "
                "(id, user_id, knowledge_point_id, status, evidence_count, "
                " self_reported_at, verified_at, created_at, updated_at) "
                "VALUES (:id, :user_id, :kp_id, :status, 0, :self_reported_at, "
                " :verified_at, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)"
            ),
            {
                "id": uuid4().hex,
                "user_id": user_id,
                "kp_id": kp_id,
                "status": target,
                "self_reported_at": (
                    started_at if status == "pending_verification" else None
                ),
                "verified_at": mastered_at,
            },
        )
        existing.add(key)


